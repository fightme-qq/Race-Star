// Единые токены раскладки. До этого файла каждый элемент носил свои магические
// числа, и они разъезжались: кнопка «Activate 2x» (центр 195, ширина 148 →
// правый край 269) залезала на «CLASSES» (левый край 249) ровно на 20px, а
// поймать это по коду было нельзя — слагаемые лежали в разных файлах.
// Теперь вертикаль экрана считается ОДНОЙ цепочкой сверху вниз, и любой сдвиг
// одного блока автоматически двигает следующий.
export const SCREEN = { w: 390, h: 844 }

// Шаг отступов. Всё в UI выравнивается по этой шкале, произвольных зазоров нет.
export const SP = { xs: 4, sm: 6, md: 10, lg: 14, xl: 20 }

export const R = { sm: 8, md: 12, lg: 16, pill: 999 }

// --- Вертикаль главного экрана ------------------------------------------
export const HEADER_H = 132
export const NAV_H = 70

export const SIDE = 10                       // боковые поля главного экрана

// --- Карточка апгрейда ---------------------------------------------------
// Высота выведена из содержимого, а не подобрана: 10 (поле) + 42 (иконка) + ...
// см. UpgradeCard.L.
export const CARD = { w: 172, h: 142, gap: 10 }

// Сетка считается СНИЗУ ВВЕРХ, от нижнего меню, и её высота выводится из
// высоты карточки, а не наоборот. Иначе нижняя кромка списка попадает в
// случайное место карточки: при GRID_H=302 она приходилась ровно на конец
// второго ряда, и полоса затухания гасила кнопки «Upgrade» вместо того, чтобы
// показать, что ниже есть ещё.
const GRID_ROWS = 2
export const GRID_PEEK = 18                  // сколько видно от третьего ряда
export const GRID_H = GRID_ROWS * (CARD.h + CARD.gap) - CARD.gap + GRID_PEEK  // 312
export const GRID_Y = SCREEN.h - NAV_H - 6 - GRID_H                           // 456

// Полоса под всплывашки. Своя, а не поверх карты: тосты приходят каждые
// несколько секунд, и на карте они закрывали ровно то место, где едут точки
// участников. Полоса фона стоит дешевле, чем закрытый игровой объект.
export const TOAST_LANE_H = 26
export const TOAST_LANE_Y = GRID_Y - 2 - TOAST_LANE_H    // 428
export const TOAST_Y = TOAST_LANE_Y + TOAST_LANE_H / 2   // 441

// Сколько плашек живёт одновременно. Стопка растёт ВВЕРХ от полосы, поэтому
// лимит — это ровно «сколько места есть выше полосы»: на главном экране выше
// лежит тёмная подложка блока гонки (две влезают), над окном — затемнённая
// шапка (три).
export const TOAST_STACK = 2

// При открытой модалке полоса уезжает НАД кромкой окна (окна начинаются с
// MODAL.top = 96): 78 + половина плашки = 92, то есть под окно она уже не
// заходит. Раньше якорь стоял на raceY+128 и внутри окна ложился поперёк
// содержимого — ловилось на кадре карьеры.
export const TOAST_MODAL_Y = 78
export const TOAST_MODAL_STACK = 3

// Блок гонки забирает всё, что осталось между шапкой и полосой тостов.
export const RACE_Y = HEADER_H + 8                       // 140
export const RACE_H = TOAST_LANE_Y - RACE_Y              // 288

// --- Модалки -------------------------------------------------------------
export const MODAL = { top: 96, bottom: 84, side: 10, pad: 12 }

// Слои. Раньше глубины стояли числами по месту (100, 150, 160, -2), и порядок
