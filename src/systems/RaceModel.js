import { RACE } from '../config/balance.js'

// Единая математика исхода заезда. Один файл на трёх потребителей: визуальную
// гонку (RaceSimulation), быструю модель стенда (tools/sim/fastrace.js) и
// аналитический оценщик бота (beatProb -> placeDist). Пока формула жила в трёх
// местах, правку защиты пришлось бы делать синхронно в трёх файлах — иначе
// подбор баланса считает по одной модели, а игрок катается по другой.
//
// МОДЕЛЬ. Заезд решается ОДНОЙ из двух сторон подготовки, какой именно —
// разыгрывается на старте:
//     с вероятностью attackWeight  гонка «на обгон»   -> в дело идёт offense
//     иначе                        гонка «на удержание» -> идёт defense
//     S = (2 * стат)^0.45 * exp(sigma * z),   z ~ N(0,1)
// Множитель 2 держит старую шкалу: у ровной команды 2*стат == сумме статов, и
// вся калибровка Этапов 1-3 не сдвигается ни на процент.
//
// ПОЧЕМУ ТАК, А НЕ ИНАЧЕ — две отвергнутых замером формы.
// До Этапа 4 место считалось по СУММЕ offense+defense, а защита гасила
// покадровый шум; тот за 600 тиков усредняется до ±0.3%, так что доллар в
// защиту и доллар в атаку давали ровно одно и то же — деление слотов было
// косметикой.
// Попытка 1 — «атака поднимает темп, защита сужает разброс». Провалилась:
// оптимум вышел «всё в атаку» в семи строках таблицы из восьми.
// Попытка 2 — среднее геометрическое статов плюс тот же разброс. Провалилась
// зеркально: оптимум встал ровно на 50/50 и никуда не поехал.
// Общая причина у обеих: побеждать надо ВСЕХ ДЕВЯТЕРЫХ, шанс на победу — это
// произведение девяти Ф, и его кривизну задают те соперники, которых игрок уже
// обыгрывает. Производная по разбросу пропорциональна сумме z по пелотону и
// отрицательна всюду, где игрок выше медианы поля. Значит на дисперсии решение
// не построить в принципе: она полезна только тому, кто и так не выигрывает.
//
// Работает разделение по ОБЪЕКТУ, а не по моменту распределения. Обе стороны
// дают выигрыш первого порядка, но каждая — в своей половине заездов, а шанс
// перестаёт быть произведением одинаковых сомножителей и становится СУММОЙ
// двух Ф. У суммы Ф кривизна меняет знак: слабому выгодно вложиться в одну
// сторону (выпуклая область — лучше выигрывать половину заездов уверенно, чем
// все никак), сильному выгоден ровный расклад (вогнутая — провал в 45%
// заездов стоит дороже прибавки в остальных). Оптимум ЕДЕТ по силе игрока —
// это и есть решение, которого в ветке не было. Проверяется прогоном
// `node tools/sim/split.js`.

const PACE_EXP = 0.45          // [X] сжатие разрыва по силе, см. baseSpeedOf
const STAT_FLOOR = 1e-6

// Расстановка соперников по силе относительно лиги. Держим здесь же: и быстрая
// модель, и оценщик обязаны видеть ровно тот же пелотон, что игрок.
export const OPPONENT_SPREAD = [0.72, 0.80, 0.87, 0.93, 1.0, 1.06, 1.13, 1.21, 1.32]

export function racerShape(off, def) {
  const o = Math.max(STAT_FLOOR, off)
  const d = Math.max(STAT_FLOOR, def)
  const power = o + d
  const m = RACE.modeShare
  return {
    power,
    tilt: d / power - 0.5,
    // Режим решает заезд не целиком: modeShare задаёт, какая доля темпа зависит
    // от профильной стороны, остальное тянет общая подготовка. При m = 1 команда
    // с раскладом 20/80 в 55% заездов приезжает последней — обрыв, а не решение.
    attack: Math.pow(power, 1 - m) * Math.pow(2 * o, m),
    hold: Math.pow(power, 1 - m) * Math.pow(2 * d, m),
    sigma: RACE.formSigma,
  }
}

// Соперник лиги: статы поровну, обе ставки равны его силе. Перекос — привилегия
// игрока, у пелотона расклад всегда ровный.
export const opponentShape = (power) => racerShape(power / 2, power / 2)

const logPace = (stat) => PACE_EXP * Math.log(Math.max(STAT_FLOOR, stat))

export function drawScore(s, rng) {
  const stat = rng.next() < RACE.attackWeight ? s.attack : s.hold
  return Math.exp(logPace(stat) + rng.gauss(0, s.sigma))
}

// --- Аналитика -----------------------------------------------------------
// Разность двух нормальных величин нормальна с sigma = sqrt(sa^2+sb^2), поэтому
// шанс обогнать считается в замкнутой форме — без единого прогона. Смесь двух
// режимов даёт четыре слагаемых; у сбалансированного соперника обе ставки
// совпадают, и сумма сворачивается в два, но общий вид дешевле поддерживать.
const erf = (x) => {
  const t = 1 / (1 + 0.3275911 * Math.abs(x))
  const y = 1 - ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t
    - 0.284496736) * t + 0.254829592) * t * Math.exp(-x * x)
  return x >= 0 ? y : -y
}

const normCdf = (z) => 0.5 * (1 + erf(z / Math.SQRT2))

// Распределение мест.
//
// Раньше здесь стояла свёртка девяти НЕЗАВИСИМЫХ «шансов обогнать», и это была
// ошибка, пережившая три этапа подбора. Девять обгонов не независимы: форма и
// режим разыгрываются игроку ОДИН раз на весь заезд, поэтому в хороший день он
// обходит всех сразу, а в плохой — никого. Положительная корреляция поднимает
// вероятность совместного события, то есть победы. Расхождение не косметическое:
// при силе/лиге 1.3 свёртка давала ~7% побед против 26% у симуляции.
//
// Отдельной функции «шанс обогнать одного» здесь СПЕЦИАЛЬНО нет. Она была,
// осталась без потребителей и звала применить себя ровно тем способом, который
// и породил ошибку.
//
// Считаем честно: фиксируем собственный результат x, при нём соперники уже
// независимы, свёртываем, и усредняем по x. Интегрирование — Симпсон по 25
// узлам на ±4 сигмы, отдельно для каждого из двух режимов.
const GRID_HALF = 4
const GRID_N = 24            // чётное — требование Симпсона
const NORM = 1 / Math.sqrt(2 * Math.PI)

export function placeDist(shape, leaguePower) {
  const mus = OPPONENT_SPREAD.map((s) => logPace(opponentShape(leaguePower * s).attack))
  const out = new Array(10).fill(0)
  const w = RACE.attackWeight
  const step = (2 * GRID_HALF) / GRID_N

  for (const [modeP, stat] of [[w, shape.attack], [1 - w, shape.hold]]) {
    const mu = logPace(stat)
    for (let i = 0; i <= GRID_N; i++) {
      const z = -GRID_HALF + i * step
      // Веса Симпсона: 1, 4, 2, 4, ... 4, 1.
      const simp = i === 0 || i === GRID_N ? 1 : i % 2 ? 4 : 2
      const weight = modeP * simp * (step / 3) * NORM * Math.exp(-z * z / 2)
      const x = mu + shape.sigma * z

      let dist = [1]
      for (const m of mus) {
        const beat = normCdf((x - m) / shape.sigma)
        const next = new Array(dist.length + 1).fill(0)
        for (let k = 0; k < dist.length; k++) {
          next[k] += dist[k] * beat
          next[k + 1] += dist[k] * (1 - beat)
        }
        dist = next
      }
      for (let k = 0; k < 10; k++) out[k] += weight * dist[k]
    }
  }
  return out
}

export const placeDistOf = (off, def, leaguePower) =>
  placeDist(racerShape(off, def), leaguePower)

// Дуэль один на один — для Champions Arena (шаг 8). Живёт ЗДЕСЬ, а не в
// ArenaSystem, по правилу 16: копия формулы заезда в другом файле означает, что
// арена оценивает силу иначе, чем трасса, и игрок, собравший команду под
// лигу, в арене проигрывает по причине, которой не видит.
//
// Это НЕ placeDist с одним соперником. Правило 17 (места не независимы) здесь
// неприменимо — соперник ровно один, свёртки нет. Зато режим разыгрывается
// ОБОИМ: и мне, и ему, поэтому исходов четыре, и веса перемножаются.
//
// [E] `Your chance of winning depends on your Team Power compared to your
// opponent's` + `Win Chance is shown during the Arena match` — то есть число
// показывается игроку, и считать его надо тем же, чем решается бой.
export function duelProb(mine, theirs) {
  const w = RACE.attackWeight
  const mix = (shape) => [[w, shape.attack], [1 - w, shape.hold]]
  let p = 0
  for (const [pm, myStat] of mix(mine)) {
    for (const [po, opStat] of mix(theirs)) {
      const sd = Math.sqrt(mine.sigma * mine.sigma + theirs.sigma * theirs.sigma)
      p += pm * po * normCdf((logPace(myStat) - logPace(opStat)) / sd)
    }
  }
  return p
}

export const duelProbOf = (off, def, oppPower) =>
  duelProb(racerShape(off, def), opponentShape(oppPower))
