// Строй пелотона: очередь по дистанции и просветы, которые в ней обязаны
// держаться. Что машина делает в борьбе — в Duel.js, как это превращается в
// движение — в RacerLayer.js.
//
// ГЛАВНОЕ РЕШЕНИЕ — КОЛОННЫ. Поперечное положение задаётся не расчётом от
// соседей каждый кадр, а КОЛОННОЙ машины: левая или правая, живёт постоянно и
// меняется одним осознанным решением — когда машина готовит обгон. Просвет
// между колоннами (2 * COL = 6.6 px при кузове 6) гарантирован КОНСТРУКЦИЕЙ.
//
// Две отвергнутых замером схемы, обе считали смещение от положения соседей:
// сила расталкивания, пропорциональная нехватке просвета, имеет равновесие
// ВНУТРИ зазора (пара сходилась на 4 px при нужных 6.6); релаксация целей по
// всем парам к требованию сходится, но зависит от порядка обхода — цели
// дёргались на 5-8 px за кадр, перестроение за ними не успевало, а для соседа
// через одного решения не было вовсе. Обе ловились стендом tools/sim/track.js
// как просвет 1-4 px при нулевой дистанции; у колонн он всегда 6.6 px.
//
// Смещение по апексу прибавляется ОБЩИМ для всех слагаемым (зависит только от
// точки трассы, а у двух машин рядом она одна), поэтому просвет между колоннами
// оно не трогает — это и позволяет держать гоночную траекторию одновременно с
// гарантией зазора.
export const NEAR = 5    // px — просвет между соседями по очереди (разные колонны)
export const PAIR = 12.5 // px — просвет между машинами В ОДНОЙ колонне (кузов 11)
export const COL = 3.3   // px — смещение колонны от осевой

const SWAP_CD = 0.6      // с — не чаще одной перестановки в очереди
const MAXSPAN = 0.45     // круга — предел визуального разброса пелотона

// Колонна, которую машина занимает ФИЗИЧЕСКИ: пока перестроение не закончено,
// она стоит поперёк обеих. Пока col переключался мгновенно, ограничение просвета
// в targets() отпускалось в тот же кадр — машина получала цель на 7.5 px вперёд
// и догоняла соседа по СТАРОЙ колонне раньше, чем уходила из неё. Это был
// последний источник грубых наложений в стенде.
export const held = (c) => (c.cross ? -c.col : c.col)

export class Formation {
  constructor(lapPx, count) {
    this.lapPx = lapPx
    this.swapCd = 0
    this.slots = []
    for (let i = 0; i < count; i++) this.slots.push(i)
  }

  // Стартовая решётка: две колонны с шагом PAIR, тот же строй, что выдаёт
  // targets(). Ставить всех в дистанцию 0 нельзя — первый кадр игры показывал
  // бы кучу из десяти машин в одной точке.
  static column(i) { return i % 2 ? 1 : -1 }
  gridDist(i) { return -(Math.floor(i / 2) * PAIR + (i % 2) * NEAR) / this.lapPx }

  // Очередь по модели — С ГИСТЕРЕЗИСОМ и не чаще одной перестановки за SWAP_CD.
  // Это ключ ко всей стабильности: в первые секунды заезда прогресс у десяти
  // машин почти равен, соседи расходятся на 3-5 px, и при пороге в один просвет
  // очередь пересобиралась каждый кадр — цели менялись быстрее, чем следящий
  // контур их отрабатывал, и машины в одной колонне съезжались в одну точку.
  // Порог поэтому равен ДЛИНЕ КУЗОВА: место отбирается, только если соперник
  // ушёл вперёд на корпус. Кулдаун — время самой рокировки.
  //
  // Визуальный порядок из-за этого на секунду-другую отстаёт от модельного —
  // осознанный размен: номер места игрок читает в бейдже P{n}/10 и на ленте
  // кругов, а на карте важнее, чтобы машины не ездили сквозь друг друга.
  reslot(cars, dt) {
    this.swapCd = Math.max(0, this.swapCd - dt)
    if (this.swapCd > 0) return
    const swap = PAIR / this.lapPx
    for (let k = 0; k < this.slots.length - 1; k++) {
      const A = cars[this.slots[k]], B = cars[this.slots[k + 1]]
      // Обогнать можно только по СОСЕДНЕЙ колонне: рокировка внутри одной
      // означала бы проезд сквозь кузов. Пока места нет — висим в слипстриме.
      if (A.col !== B.col && B.simDist > A.simDist + swap) {
        this.slots[k] = B.i
        this.slots[k + 1] = A.i
        this.swapCd = SWAP_CD
        return
      }
    }
  }

  // Цели по дистанции: разрывы модели, но НЕ УЖЕ, чем физически помещается.
  // Ограничения два и оба обязательны: соседи по очереди не ближе NEAR (иначе
  // при сбросе заезда цель у всех десяти — одна точка), а машины В ОДНОЙ
  // КОЛОННЕ — не ближе длины кузова. Второе и позволяет паре из разных колонн
  // идти борт о борт, не наезжая друг на друга.
  targets(cars, mean, pack) {
    const near = NEAR / this.lapPx
    const pair = PAIR / this.lapPx
    const lastInCol = { '-1': null, 1: null }
    // Сжатие разброса. К концу заезда форма растаскивает пелотон на 2+ КРУГА:
    // лидер обгоняет хвост на круг, и на карте они оказываются в одном кузове,
    // хотя по дистанции между ними полгонки. Сжимаем линейно — порядок и все
    // минимальные просветы сохраняются, разрывы остаются пропорциональными.
    // Истинный прогресс каждого виден на ленте кругов над картой.
    let lo = 1e9, hi = -1e9
    for (const c of cars) {
      if (c.simDist < lo) lo = c.simDist
      if (c.simDist > hi) hi = c.simDist
    }
    const scale = hi - lo > MAXSPAN ? MAXSPAN / (hi - lo) : 1

    const t = []
    let sum = 0
    for (let k = 0; k < this.slots.length; k++) {
      const car = cars[this.slots[k]]
      let v = (car.simDist - mean) * scale
      if (k >= 1) v = Math.min(v, t[k - 1] - near)
      const col = held(car)
      const same = lastInCol[col]
      if (same !== null) v = Math.min(v, same - pair)
      lastInCol[col] = v
      t.push(v)
      sum += v
    }
    // Центрируем: подрезка сдвигает строй назад, а пелотон должен ехать ровно
    // с тем темпом, что даёт модель, без медленного отставания от pack.
    const shift = sum / t.length
    const out = []
    for (let k = 0; k < this.slots.length; k++) out[this.slots[k]] = pack + t[k] - shift
    return out
  }
}
